                        icon = Icons.Default.CheckCircle,
                        title = "Daily Budget Limits",
                        desc = "Real-time daily expense monitoring against your target."
                    )
                    FeatureHighlightRow(
                        icon = Icons.Default.Savings,
                        title = "Targeted Savings Goals",
                        desc = "Visual milestones for vacations, emergencies & purchases."
                    )
                    FeatureHighlightRow(
                        icon = Icons.Default.Shield,
                        title = "Cloud Sync & Security",
                        desc = "Zero-trust encrypted database powered by Firebase."
                    )
                }
            }

            Spacer(modifier = Modifier.height(32.dp))

